from __future__ import annotations

from argparse import ArgumentParser
from typing import Any
from uuid import uuid4

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from modules.common.local_database import require_pg_tool, run_pg_tool
from modules.common.remote_backup import (
    configured_database,
    remove_temporary_directory,
    temporary_backup_directory,
    upload_verified_archive,
)


class Command(BaseCommand):
    help = "Create and remotely verify an encrypted, versioned PostgreSQL backup."

    def add_arguments(self, parser: ArgumentParser) -> None:
        parser.add_argument(
            "--backup-id", help="Optional UUID for this backup (generated by default)."
        )

    def handle(self, *args: object, **options: Any) -> None:
        del args
        if not settings.REMOTE_DATABASE_BACKUP_ENABLED:
            raise CommandError("Remote database backup is disabled by configuration.")
        database = configured_database()
        backup_id = str(options["backup_id"] or uuid4())
        temporary_directory = temporary_backup_directory()
        archive = temporary_directory / "database.dump"
        try:
            archive.touch(mode=0o600, exist_ok=False)
            executable = require_pg_tool("pg_dump")
            run_pg_tool(
                [
                    executable,
                    "--no-password",
                    "--format=custom",
                    f"--host={database['host']}",
                    f"--port={database['port']}",
                    f"--username={database['user']}",
                    f"--dbname={database['name']}",
                    f"--file={archive}",
                ],
                database=database,
            )
            receipt = upload_verified_archive(archive, backup_id=backup_id)
        finally:
            remove_temporary_directory(temporary_directory)
        self.stdout.write(
            self.style.SUCCESS(
                "Remote backup verified: "
                f"backup_id={receipt.backup_id} key={receipt.object_key} "
                f"version_id={receipt.version_id} size={receipt.size_bytes} "
                f"sha256={receipt.sha256} retention_until={receipt.retention_until}"
            )
        )
